/**
 * Защита от самоодобрения при прерывании голосом.
 *
 * Во время речи приложения микрофон слушает: так вас слышно и можно перебить.
 * Эхоподавление не идеально, и остаток собственной речи из колонок может
 * распознаться как фраза — например, «скажите „выполняй“» одобрила бы план сама.
 *
 * Эхо — это сказанное приложением, услышанное подряд и почти дословно. Поэтому
 * сверяем по порядку слов, а не по набору: слова услышанной фразы должны идти
 * в сказанном в том же порядке и рядом друг с другом. Реплика на ту же тему
 * («переделай кнопку меню» во время рассказа о кнопке меню) так не совпадёт.
 * Служебные слова («не», «это», «что») не учитываем — они есть в любом тексте.
 * Слова сравниваются целиком: «переделай» в вашей реплике — не «переделал» из
 * ответа. Ошибки распознавания самого эха покрывает порог `ECHO_SHARE`.
 * Сверять стоит только с фразами, звучавшими, пока вы говорили (`speech.ts`).
 *
 * Цена: ваше «выполняй» поверх фразы «скажите „выполняй“» тоже отбросится.
 * Речь при этом уже оборвана — повторите ещё раз.
 */

/** Доля слов фразы, найденных в сказанном по порядку и рядом, начиная с которой фраза — эхо. */
export const ECHO_SHARE = 0.7

/** Служебные слова: встречаются в любом тексте и ничего не говорят о совпадении. */
const STOP_WORDS = new Set([
  'это', 'что', 'как', 'так', 'вот', 'еще', 'уже', 'или', 'для', 'при', 'его', 'она',
  'они', 'оно', 'мне', 'все', 'был', 'была', 'было', 'тот', 'там', 'тут', 'нет', 'если',
  'чтобы', 'когда', 'тоже', 'только', 'этот', 'эта', 'эти', 'вас', 'вам', 'нас', 'них'
])

function words(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^\p{L}\p{N}]+/u)
    .filter(Boolean)
}

/** Значимое слово: не короткое и не служебное. */
const isContent = (word: string): boolean => word.length > 2 && !STOP_WORDS.has(word)

/** Длина наибольшей общей подпоследовательности. */
function lcs(a: readonly string[], b: readonly string[]): number {
  let prev = new Array<number>(b.length + 1).fill(0)
  for (const x of a) {
    const row = new Array<number>(b.length + 1).fill(0)
    for (let j = 0; j < b.length; j++) {
      row[j + 1] = x === b[j] ? prev[j]! + 1 : Math.max(prev[j + 1]!, row[j]!)
    }
    prev = row
  }
  return prev[b.length]!
}

/**
 * Услышанная фраза — это эхо сказанного приложением? Слова фразы ищутся по
 * порядку в окне сказанного длиной чуть больше самой фразы: эхо идёт подряд.
 */
export function isEcho(heard: string, spoken: readonly string[]): boolean {
  const all = words(heard)
  // Сверяем значимые слова; если их меньше двух — все (иначе «выполняй» не с чем сверять).
  const useContent = all.filter(isContent).length >= 2
  const pick = (ws: string[]): string[] => useContent ? ws.filter(isContent) : ws
  const h = pick(all)
  const s = spoken.flatMap((text) => pick(words(text)))
  if (h.length === 0 || s.length === 0) return false
  const window = h.length * 2 + 2
  let best = 0
  for (let start = 0; start < s.length && best < h.length; start++) {
    best = Math.max(best, lcs(h, s.slice(start, start + window)))
  }
  return best / h.length >= ECHO_SHARE
}
