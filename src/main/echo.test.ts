import { test } from 'node:test'
import assert from 'node:assert/strict'
import { isEcho } from '../shared/echo.ts'

const SPOKEN = ['План готов. Скажите «выполняй», чтобы начать, или скажите, что поправить.']

/** Длинный ответ, прочитанный вслух: сотни слов, служебные и по теме. */
const LONG_REPLY = [
  'Я переделал кнопку меню в верхней панели: теперь она открывает список проектов.',
  'Это было нужно, потому что старая кнопка меню не реагировала на клавиатуру,',
  'и что-то в её обработчике ломалось при повторном нажатии. Я не стал менять стили,',
  'только логику: кнопка меню теперь закрывает список по Esc, а если список пуст,',
  'показывает подсказку. Тесты для меню добавлены, всё проходит. Скажите, что дальше.'
]

test('собственная фраза приложения, услышанная микрофоном, — эхо', () => {
  assert.equal(isEcho('скажите выполняй', SPOKEN), true)
  assert.equal(isEcho('Выполняй.', SPOKEN), true)
  // Распознавание эха неточное: одно слово искажено, но остальные идут подряд и по порядку.
  assert.equal(isEcho('план готов скажите выполнять чтобы начать', SPOKEN), true)
  assert.equal(
    isEcho('кнопка меню теперь закрывает список по эскейп', LONG_REPLY),
    true,
    'кусок длинного ответа с одной ошибкой распознавания'
  )
})

test('ваша реплика поверх длинного ответа на ту же тему — не эхо', () => {
  assert.equal(isEcho('нет, это не то, что я просил', LONG_REPLY), false)
  assert.equal(isEcho('переделай кнопку меню', LONG_REPLY), false)
  assert.equal(isEcho('стоп, добавь ещё тесты для меню', LONG_REPLY), false)
  assert.equal(isEcho('а список проектов где', LONG_REPLY), false)
})

test('ваша реплика поверх короткой фразы — не эхо', () => {
  assert.equal(isEcho('Стоп, добавь ещё тесты для парсера', SPOKEN), false)
  assert.equal(isEcho('нет, переделай кнопку', SPOKEN), false)
})

test('слова в другом порядке и вразброс — не эхо', () => {
  assert.equal(isEcho('меню кнопка список проектов панели', LONG_REPLY), false)
})

test('регистр, ё и знаки препинания не мешают сравнению', () => {
  assert.equal(isEcho('ВСЁ ГОТОВО!', ['Все готово.']), true)
})

test('пустая фраза или ничего не сказано — не эхо', () => {
  assert.equal(isEcho('  ', SPOKEN), false)
  assert.equal(isEcho('выполняй', []), false)
})
